/**
 * Regenerates sitemap-images.xml from the <img> tags actually used on each indexable page,
 * and updates <lastmod> in sitemap.xml for pages whose files changed since a git ref.
 *
 * Usage: node scripts/build-sitemaps.js [git-ref-for-lastmod]
 *   e.g. node scripts/build-sitemaps.js backup-pre-seo-execution-2026-11-14
 */
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const ORIGIN = 'https://khaleejjeddah.com';
const SKIP = new Set(['node_modules', '.git', 'assets', 'dist', 'src', 'favicon', 'scripts']);

function listPages(dir, out = []) {
    for (const f of fs.readdirSync(dir)) {
        if (SKIP.has(f)) continue;
        const p = path.join(dir, f);
        if (fs.statSync(p).isDirectory()) listPages(p, out);
        else if (f === 'index.html') out.push(p);
    }
    return out;
}
const urlOf = f => {
    const r = path.relative(ROOT, f).replace(/\\/g, '/');
    return r === 'index.html' ? '/' : '/' + r.replace(/index\.html$/, '');
};
const xmlEsc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

// ---- sitemap-images.xml
const entries = [];
for (const file of listPages(ROOT).sort()) {
    const html = fs.readFileSync(file, 'utf8');
    if (/<meta\s+name="robots"[^>]*noindex/i.test(html)) continue;
    const body = (html.match(/<body[\s\S]*<\/body>/i) || [''])[0]
        .replace(/<footer[\s\S]*?<\/footer>/gi, '').replace(/<nav[\s\S]*?<\/nav>/gi, '');
    const imgs = new Set();
    for (const m of body.matchAll(/<img\b[^>]*\bsrc="(\/assets\/img\/[^"]+)"/gi)) {
        if (/logo\.webp$/.test(m[1])) continue;
        imgs.add(ORIGIN + m[1].split('/').map(encodeURIComponent).join('/').replace(/%2F/g, '/'));
    }
    if (imgs.size) entries.push([ORIGIN + urlOf(file), [...imgs]]);
}
const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/build-sitemaps.js — do not edit by hand -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"
        xmlns:image="http://www.google.com/schemas/sitemap-image/1.1">
${entries.map(([loc, imgs]) => `  <url>
    <loc>${xmlEsc(loc)}</loc>
${imgs.map(i => `    <image:image>
      <image:loc>${xmlEsc(i)}</image:loc>
    </image:image>`).join('\n')}
  </url>`).join('\n')}
</urlset>
`;
fs.writeFileSync(path.join(ROOT, 'sitemap-images.xml'), xml);
console.log(`sitemap-images.xml: ${entries.length} pages, ${entries.reduce((n, e) => n + e[1].length, 0)} images`);

// ---- sitemap.xml lastmod
const ref = process.argv[2];
if (ref) {
    const today = new Date().toISOString().slice(0, 10);
    const changed = execSync(`git diff --name-only ${ref} -- "*.html"`, { cwd: ROOT }).toString().trim().split('\n').filter(Boolean)
        .filter(f => f.endsWith('index.html'))
        .map(f => ORIGIN + (f === 'index.html' ? '/' : '/' + f.replace(/index\.html$/, '')));
    let sm = fs.readFileSync(path.join(ROOT, 'sitemap.xml'), 'utf8');
    let n = 0;
    for (const loc of changed) {
        const re = new RegExp(`(<loc>${loc.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}</loc>\\s*<lastmod>)[^<]*`);
        if (re.test(sm)) { sm = sm.replace(re, `$1${today}`); n++; }
    }
    fs.writeFileSync(path.join(ROOT, 'sitemap.xml'), sm);
    console.log(`sitemap.xml: lastmod set to ${today} for ${n} changed page(s)`);
}
